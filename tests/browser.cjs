const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { once } = require('node:events');
const { chromium, expect } = require('@playwright/test');
const { createApp } = require('../dist/server/main.js');

async function main() {
  const root = path.resolve('.test-data');
  fs.mkdirSync(root, { recursive: true });
  const dataDir = fs.mkdtempSync(path.join(root, 'browser-'));
  const server = createApp({ dataDir }).listen(0, '127.0.0.1');
  await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  let browser;
  try {
    browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
    const context = await browser.newContext();
    context.setDefaultTimeout(15000);
    const page = await context.newPage();
    const pageErrors = [];
    page.on('pageerror', error => pageErrors.push(error.message));
    await page.route('https://cdn.jsdelivr.net/**', route => route.abort());
    await page.goto(base);
    await expect(page.locator('#serverStatus')).toContainText('Đã kết nối');
    await page.locator('#gateTabRegister').click();
    await page.locator('#gateRegUser').fill('BrowserPlayer');
    await page.locator('#gateRegEmail').fill('browser@example.test');
    await page.locator('#gateRegPass').fill('password123');
    await page.locator('#btnGateSubmitRegister').click();
    await expect(page.locator('#arenaAppContainer')).toBeVisible();
    await expect(page.locator('#usernameInput')).toHaveValue('BrowserPlayer');
    await expect(page.locator('#codeEditor')).toHaveValue(/import/);
    await page.locator('#testBotSelect').selectOption('1');
    await page.locator('#btnTestMatch').click();
    await expect(page.locator('#botTestCountBadge')).toHaveText('1', { timeout: 60000 });
    await expect(page.locator('#botTestMatchesGrid .match-card')).toHaveCount(1);
    page.on('dialog', dialog => dialog.accept());
    await page.locator('[onclick="handleLogout()"]').click();
    await expect(page.locator('#authGatewayScreen')).toBeVisible();
    await expect(page.locator('#serverStatus')).toHaveText('Đã kết nối máy chủ đấu trường.');
    await expect(page.locator('#botTestCountBadge')).toHaveText('0');
    await page.locator('#gateLoginId').fill('BrowserPlayer');
    await page.locator('#gateLoginPass').fill('password123');
    await page.locator('#btnGateSubmitLogin').click();
    await expect(page.locator('#arenaAppContainer')).toBeVisible();
    await page.locator('[data-maintab="ladder"]').click();
    await page.locator('#btnSubmitRank').click();
    await expect(page.locator('#serverStatus')).toContainText('Đã lưu bài', { timeout: 120000 });
    await expect(page.locator('#submissionHistory .submission-history-row')).toHaveCount(1);
    const downloaded = page.waitForEvent('download');
    await page.locator('#btnDownloadLog').click();
    const logDownload = await downloaded;
    const log = JSON.parse(fs.readFileSync(await logDownload.path(), 'utf8'));
    assert.equal(log.username, 'BrowserPlayer');
    assert.equal(log.schemaVersion, 1);
    assert.ok(log.matches.length);
    assert.equal(log.sourceCode, undefined);
    await page.reload();
    await expect(page.locator('#arenaAppContainer')).toBeVisible();
    await expect(page.locator('#submissionHistory .submission-history-row')).toHaveCount(1);
    await page.locator('#submissionHistory button').first().click();
    await expect(page.locator('#gauntletMatchesGrid .match-card')).not.toHaveCount(0);
    // A separate browser session signs into the same server-owned account and sees its records.
    const secondContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    secondContext.setDefaultTimeout(15000);
    const second = await secondContext.newPage();
    second.on('pageerror', error => pageErrors.push(error.message));
    await second.route('https://cdn.jsdelivr.net/**', route => route.abort());
    await second.goto(base);
    await second.locator('#gateLoginId').fill('BrowserPlayer');
    await second.locator('#gateLoginPass').fill('password123');
    await second.locator('#btnGateSubmitLogin').click();
    await expect(second.locator('#arenaAppContainer')).toBeVisible();
    await expect(second.locator('#submissionHistory .submission-history-row')).toHaveCount(1);
    await second.locator('[data-lang="java"]').click();
    await second.locator('#testBotSelect').selectOption('1');
    await second.locator('#btnTestMatch').click();
    await expect(second.locator('#botTestCountBadge')).toHaveText('1', { timeout: 60000 });
    await expect(second.locator('#serverStatus')).toContainText('Đã hoàn tất');
    await second.locator('[data-maintab="ladder"]').click();
    await second.locator('#btnSubmitRank').click();
    await expect(second.locator('#serverStatus')).toContainText('Đã lưu bài', { timeout: 120000 });
    await expect(second.locator('#submissionHistory .submission-history-row')).toHaveCount(2);
    await second.locator('[data-maintab="studio"]').click();
    // Compiler errors must be visible and persisted, without a success/Top #1 banner.
    await second.locator('#codeEditor').fill('this is not java');
    await second.locator('[data-maintab="ladder"]').click();
    await second.locator('#btnSubmitRank').click();
    await expect(second.locator('#gauntletSummaryBanner')).toContainText('Lỗi biên dịch', { timeout: 60000 });
    await expect(second.locator('#submissionHistory .submission-history-row')).toHaveCount(3);
    await expect(second.locator('#matchSummaryTag')).toContainText('Chọn một trận');
        assert.ok(await second.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile page must fit viewport');
    await second.screenshot({ path: path.join(root, 'mobile-result.png'), fullPage: true });
    second.on('dialog', dialog => dialog.accept());
    await second.locator('[onclick="handleLogout()"]').click();
    await expect(second.locator('#authGatewayScreen')).toBeVisible();
    await expect(second.locator('#serverStatus')).toHaveText('Đã kết nối máy chủ đấu trường.');
    await expect(second.locator('#serverStatus')).not.toHaveClass(/server-error/);
    assert.deepEqual(pageErrors, []);
    await page.screenshot({ path: path.join(root, 'desktop-result.png'), fullPage: true });
    // A response arriving after logout must not restore the previous session's message.
    let releaseResponse;
    let markRequested;
    const responseGate = new Promise(resolve => { releaseResponse = resolve; });
    const requested = new Promise(resolve => { markRequested = resolve; });
    await page.route('**/api/test-match', async route => {
      markRequested();
      await responseGate;
      await route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'Late match error' }) });
    });
    await page.locator('[data-maintab="studio"]').click();
    await page.locator('#btnTestMatch').click();
    await requested;
    await page.locator('[onclick="handleLogout()"]').click();
    await expect(page.locator('#authGatewayScreen')).toBeVisible();
    releaseResponse();
    await expect(page.locator('#btnTestMatch')).toBeEnabled();
    await expect(page.locator('#serverStatus')).toHaveText('Đã kết nối máy chủ đấu trường.');
    console.log('PASS: browser registration, Python match/submission, replay/log download, reload, second-browser login, Java match, compiler error and logout.');
  } finally {
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
    if (!dataDir.startsWith(root + path.sep)) throw new Error('Unexpected test directory');
    fs.rmSync(dataDir, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
